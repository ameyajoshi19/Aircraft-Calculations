export const MAX_CRUISE_PERCENT_MCP = 80;

/**
 * POH Figure 4-3 note (page 4-34): the cruise charts assume maximum gross
 * weight. Below it, TAS increases by roughly 1 knot per 150 lb under at
 * 55-80% power, or 1 knot per 125 lb under at powers below 70%.
 */
export function trueAirspeedWeightCorrectionKts(
  weightLbs: number,
  maxGrossLbs: number,
  percentPower: number
): number {
  const below = Math.max(maxGrossLbs - weightLbs, 0);
  return below / (percentPower < 70 ? 125 : 150);
}
